def apply_extensive_translations():
    files = [
        "static/index.html",
        "static/js/app.js",
        "static/js/admin.js",
        "static/js/trainer.js",
        "static/js/student.js"
    ]

    for fpath in files:
        with open(fpath, "r", encoding="utf-8") as f:
            content = f.read()

        for tr, en in EXTENSIVE_TRANSLATIONS:
            content = content.replace(tr, en)

        with open(fpath, "w", encoding="utf-8") as f:
            f.write(content)

        print(f"✓ Applied extensive translations to: {fpath}")

apply_extensive_translations()
print("ALL_TRANSLATIONS_APPLIED_SUCCESSFULLY")
